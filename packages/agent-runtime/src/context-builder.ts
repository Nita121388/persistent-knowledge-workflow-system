import type { CaseSession } from './types.js';
import { Action, DEFAULTS } from './types.js';

/**
 * Build the CLAUDE.md context string from a CaseSession.
 *
 * @param session - The active CaseSession
 * @param action - The decided action
 * @returns CLAUDE.md content as a string
 */
export function buildContext(session: CaseSession, action: Action): string {
  switch (action) {
    case Action.NewTurn:
      return buildFreshClaudeMd(session);
    case Action.Continue:
      return buildClaudeMdWithHistory(session);
    case Action.CompressThenContinue:
      return buildClaudeMdCompressed(session);
  }
}

/**
 * Helper: build the base CLAUDE.md preamble shared by all modes.
 */
function buildPreamble(session: CaseSession): string[] {
  const lines: string[] = [];

  lines.push('# CLAUDE.md — Auto-generated by PKWS Agent Runtime');
  lines.push('');
  lines.push('## PKWS Case Context');
  lines.push('');
  lines.push('### Case ID');
  lines.push(session.caseId);
  lines.push('');

  if (session.caseInstructions) {
    lines.push('### Case Instructions');
    lines.push(session.caseInstructions);
    lines.push('');
  }

  if (session.workspaceRules.length > 0) {
    lines.push('### Workspace Rules');
    for (const rule of session.workspaceRules) {
      lines.push(`- **${rule.title}**: ${rule.content}`);
    }
    lines.push('');
  }

  if (session.systemPrompt) {
    lines.push('### System Directives');
    lines.push(session.systemPrompt);
    lines.push('');
  }

  return lines;
}

/**
 * Action.NewTurn: Build a fresh CLAUDE.md from SQLite-loaded session data.
 * This is the first turn or a full context rebuild after eviction recovery.
 */
function buildFreshClaudeMd(session: CaseSession): string {
  const lines = buildPreamble(session);

  if (session.messages.length > 0) {
    lines.push('### Conversation History');
    lines.push('');
    for (const msg of session.messages) {
      const label = msg.role === 'user' ? 'Human' : msg.role === 'assistant' ? 'Assistant' : 'System';
      lines.push(`${label}: ${msg.content}`);
      lines.push('');
    }

    lines.push('### Current Task');
    lines.push('Continue the work from the conversation above. Respond to the most recent Human message.');
    lines.push('');
  } else {
    lines.push('### Current Task');
    lines.push('Analyze the case content and generate a proposal. Follow the Case Instructions and Workspace Rules.');
    lines.push('');
  }

  lines.push('### Output Requirements');
  lines.push('1. Output your analysis as a structured proposal.');
  lines.push('2. If you need user input, clearly state what you need.');
  lines.push('3. Use markdown formatting.');
  lines.push('');

  return lines.join('\n');
}

/**
 * Action.Continue: Append the latest user input to existing messages.
 * This is the common case — conversation is already in memory.
 */
function buildClaudeMdWithHistory(session: CaseSession): string {
  const lines = buildPreamble(session);

  lines.push('### Conversation History');
  lines.push('Below is the ongoing conversation. Continue from the most recent message.');
  lines.push('');

  for (const msg of session.messages) {
    const label = msg.role === 'user' ? 'Human' : msg.role === 'assistant' ? 'Assistant' : 'System';
    lines.push(`${label}: ${msg.content}`);
    lines.push('');
  }

  lines.push('### Output Requirements');
  lines.push('1. Respond to the most recent Human message.');
  lines.push('2. If you need user input, clearly state what you need.');
  lines.push('3. Use markdown formatting.');
  lines.push('');

  return lines.join('\n');
}

/**
 * Action.CompressThenContinue: Compact old messages into a summary,
 * keep the most recent N messages, then continue.
 */
function buildClaudeMdCompressed(session: CaseSession): string {
  const lines = buildPreamble(session);

  lines.push('### Conversation History');
  lines.push('');

  if (session.compressedSummary) {
    lines.push('#### Earlier Conversation (compressed)');
    lines.push(session.compressedSummary);
    lines.push('');
  }

  // Show recent messages
  const keepCount = DEFAULTS.contextKeepRecentCount;
  const recentMessages = session.messages.slice(-keepCount);

  lines.push(`#### Recent Messages (last ${recentMessages.length})`);
  lines.push('');
  for (const msg of recentMessages) {
    const label = msg.role === 'user' ? 'Human' : msg.role === 'assistant' ? 'Assistant' : 'System';
    lines.push(`${label}: ${msg.content}`);
    lines.push('');
  }

  lines.push('### Output Requirements');
  lines.push('1. Respond to the most recent Human message.');
  lines.push('2. Reference the compressed earlier conversation if needed.');
  lines.push('3. If you need user input, clearly state what you need.');
  lines.push('4. Use markdown formatting.');
  lines.push('');

  return lines.join('\n');
}

/**
 * Estimate token count of a string (rough: ~4 chars per token).
 */
export function estimateTokens(text: string): number {
  return Math.ceil(text.length / 4);
}

/**
 * Perform compression on a session: fold old messages into a summary,
 * keep only the most recent N messages.
 * Mutates the session in place.
 */
export function compressSession(session: CaseSession): void {
  const keepRecent = DEFAULTS.contextKeepRecentCount;
  const totalMessages = session.messages.length;

  if (totalMessages <= keepRecent) return;

  const oldMessages = session.messages.slice(0, totalMessages - keepRecent);
  const summary = oldMessages
    .map(m => `[${m.role}]: ${m.content.slice(0, 150)}`)
    .join('; ');

  session.compressedSummary = session.compressedSummary
    ? `${session.compressedSummary}\n[Epoch ${session.compressionEpoch + 1}] ${summary}`
    : `[Epoch ${session.compressionEpoch + 1}] ${summary}`;

  session.messages = session.messages.slice(-keepRecent);
  session.compressionEpoch++;
}
